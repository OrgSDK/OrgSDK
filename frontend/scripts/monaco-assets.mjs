import { cp, mkdir } from "node:fs/promises";
const checkOnly = process.argv.includes("--check");
if (!checkOnly) {
  const target = new URL("../public/monaco/vs/", import.meta.url);
  await mkdir(target, { recursive: true });
  await cp(
    new URL("../node_modules/monaco-editor/min/vs/", import.meta.url),
    target,
    { recursive: true },
  );
}

// Build browser declarations from the same safe renderer used by execution.
const { readFile, writeFile, readdir } = await import("node:fs/promises");
await saveGenerated(
  new URL("../public/LICENSE.txt", import.meta.url),
  await readFile(new URL("../../LICENSE", import.meta.url), "utf8"),
);
const renderer = await readFile(
  new URL("../../runtime/src/sdk-declarations.ts", import.meta.url),
  "utf8",
);
const namespaceSource = await readFile(
  new URL("../../runtime/src/engine/plugins/namespace.ts", import.meta.url),
  "utf8",
);
const { default: ts } = await import("typescript");
const namespaceAST = ts.createSourceFile(
  "namespace.ts",
  namespaceSource,
  ts.ScriptTarget.Latest,
  true,
);
const reservedNames = [
  "RESERVED_NAMESPACE_IDENTIFIERS",
  "RESERVED_FUNCTION_KEYS",
];
const reservedSets = reservedNames
  .map((name) => {
    const statement = namespaceAST.statements.find(
      (node) =>
        ts.isVariableStatement(node) &&
        node.declarationList.declarations.some(
          (declaration) =>
            ts.isIdentifier(declaration.name) && declaration.name.text === name,
        ),
    );
    if (!statement || !ts.isVariableStatement(statement))
      throw new Error(`Missing runtime namespace contract: ${name}`);
    return `const ${statement.declarationList.declarations.map((node) => node.getText(namespaceAST)).join(", ")};`;
  })
  .join("\n");
const rendererAST = ts.createSourceFile(
  "sdk-declarations.ts",
  renderer,
  ts.ScriptTarget.Latest,
  true,
);
const imports = rendererAST.statements.filter(
  (node) =>
    ts.isImportDeclaration(node) &&
    ts.isStringLiteral(node.moduleSpecifier) &&
    node.moduleSpecifier.text === "./engine/plugins/namespace",
);
if (imports.length !== 1)
  throw new Error("Expected exactly one runtime namespace import");
const namespaceImport = imports[0];
const browserRenderer =
  renderer.slice(0, namespaceImport.getStart(rendererAST)) +
  reservedSets +
  renderer.slice(namespaceImport.end);
const { format } = await import("prettier");
const generated = new URL("../src/generated/", import.meta.url);
await mkdir(generated, { recursive: true });
await saveGenerated(
  new URL("sdk-declarations.ts", generated),
  await format(
    "// Generated by scripts/monaco-assets.mjs from runtime/src/sdk-declarations.ts.\n" +
      browserRenderer,
    { parser: "typescript" },
  ),
);
const licenseDirectory = new URL(
  "../public/third-party-licenses/",
  import.meta.url,
);
await mkdir(licenseDirectory, { recursive: true });
for (const packageName of ["zod", "monaco-editor"]) {
  await saveGenerated(
    new URL(`${packageName}.txt`, licenseDirectory),
    await readFile(
      new URL(`../node_modules/${packageName}/LICENSE`, import.meta.url),
      "utf8",
    ),
  );
}

const libraries = {};
async function collectZod(directory, relative = "") {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = `${relative}${entry.name}`;
    if (entry.isDirectory())
      await collectZod(new URL(`${entry.name}/`, directory), `${path}/`);
    else if (entry.name.endsWith(".d.ts"))
      libraries[`file:///node_modules/zod/${path}`] = await readFile(
        new URL(entry.name, directory),
        "utf8",
      );
  }
}
await collectZod(new URL("../node_modules/zod/", import.meta.url));
// Monaco's Node resolver uses index.d.ts and follows Zod's relative imports.
await saveGenerated(
  new URL("zod-libraries.json", generated),
  await format(JSON.stringify(libraries), { parser: "json" }),
);

async function saveGenerated(path, content) {
  if (!checkOnly) {
    await writeFile(path, content);
    return;
  }
  const existing = await readFile(path, "utf8").catch(() => "");
  if (existing !== content)
    throw new Error(
      `Generated editor SDK drift: ${path.pathname}. Run node scripts/monaco-assets.mjs.`,
    );
}
