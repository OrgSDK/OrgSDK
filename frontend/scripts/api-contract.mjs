import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const frontend = fileURLToPath(new URL("../", import.meta.url));
const repository = fileURLToPath(new URL("../../", import.meta.url));
const temporary = await mkdtemp(join(tmpdir(), "django-template-api-"));
const check = process.argv.includes("--check");

try {
  const schemaPath = join(temporary, "openapi.json");
  execFileSync(
    "uv",
    [
      "run",
      "--locked",
      "manage.py",
      "spectacular",
      "--settings=config.settings.test",
      "--format",
      "openapi-json",
      "--validate",
      "--fail-on-warn",
      "--file",
      schemaPath,
    ],
    { cwd: repository, stdio: "inherit" },
  );
  const schema = await readFile(schemaPath, "utf8");
  const types = astToString(await openapiTS(JSON.parse(schema)));
  const authSchema = execFileSync(
    "uv",
    [
      "run",
      "--locked",
      "manage.py",
      "auth_schema",
      "--settings=config.settings.test",
    ],
    { cwd: repository, encoding: "utf8" },
  );
  const authTypes = astToString(await openapiTS(JSON.parse(authSchema)));
  const outputs = new Map([
    ["auth-openapi.json", authSchema],
    [
      "src/api/auth-schema.d.ts",
      `/** Generated by make api-generate. Do not edit. */\n${authTypes}`,
    ],
    ["openapi.json", schema],
    [
      "../runtime/src/generated/schema.d.ts",
      `/** Generated by make api-generate. Do not edit. */\n${types}`,
    ],
    [
      "src/api/schema.d.ts",
      `/** Generated by npm run api:generate. Do not edit. */\n${types}`,
    ],
  ]);
  for (const [relative, contents] of outputs) {
    const path = join(frontend, relative);
    if (!check) {
      await writeFile(path, contents);
      continue;
    }
    const existing = await readFile(path, "utf8").catch(() => undefined);
    if (existing !== contents) {
      throw new Error(
        `${relative} is stale. Run make api-generate and commit all generated API artifacts.`,
      );
    }
  }
  console.log(
    check
      ? "API contract is current."
      : "API schema and TypeScript types generated.",
  );
} finally {
  await rm(temporary, { recursive: true, force: true });
}
